from pathlib import Path
import sys,json,hashlib
import numpy as np
import pandas as pd
import torch,joblib
from sklearn.metrics import f1_score
sys.path.insert(0,'/home/adhikkesh/adhikkesh/FYP/Kaggle_P1_P5/fast_2h')
import fyp_fast as f
BASE=Path('/home/adhikkesh/adhikkesh/FYP/Kaggle_P1_P5/results_audit_20261017')
RUN=BASE/'run/FYP_FAST_2H_20261017_010129';OUT=RUN/'results'
torch.set_num_threads(2)
streams=joblib.load(RUN/'cache/prepared_streams.joblib')
report=dict(archive_crc='passed',all_five_fold_markers=all((OUT/p/'complete.json').exists() for p in f.PIDS),
 dataset=str(json.loads((OUT/'dataset_info.json').read_text())['dataset']),training_executed_locally=False,
 probe_note='Diagnostic balanced random windows, known central labels, CPU forward only. Not a new held-out event score.',probes=[],fold_histories=[])
rng=np.random.default_rng(20261017)
for pid in f.PIDS+['ALL5']:
 folder=OUT/pid/'models/seed_17' if pid!='ALL5' else OUT/'deployment_all5/seed_17'
 # User's own checkpoint, generated by this notebook; no untrusted model downloads.
 ck=torch.load(folder/'best.pt',map_location='cpu',weights_only=False)
 net=f.CSIModel(ck['arch']).eval();net.load_state_dict(ck['model'])
 for split in (['train','test'] if pid!='ALL5' else ['train']):
  subset=[s for s in streams if pid=='ALL5' or ((s['pid']!=pid)==(split=='train'))]
  rows=f.examples(subset);w=f.sampling_weights(subset,rows).numpy();w=w/w.sum()
  picked=rng.choice(len(rows),size=768,replace=True,p=w)
  ds=f.WindowDataset(subset,rows[picked],ck['scale'],ck['arch']['seconds'])
  ps=[];pf=[];ys=[];yf=[]
  with torch.inference_mode():
   for start in range(0,len(ds),128):
    items=[ds[i] for i in range(start,min(start+128,len(ds)))];x=torch.stack([a[0] for a in items]);a,b=net(x)
    ps.append(a.numpy());pf.append(b.numpy());ys.extend(a[1] for a in items);yf.extend(a[2] for a in items)
  ps=np.concatenate(ps);pf=np.concatenate(pf);ys=np.array(ys);yf=np.array(yf)
  result=dict(pid=pid,split=split,available_windows=len(rows),epochs=int(ck['epoch']),state_accuracy=float((ps.argmax(1)==ys).mean()))
  for typ,idx,start,end in [('activity',1,0,12),('sign',2,12,26)]:
   m=(ys==idx)&(yf>=0)
   pred=start+pf[m,start:end].argmax(1)
   result[typ+'_typed_accuracy']=float((pred==yf[m]).mean())
  report['probes'].append(result);print(result,flush=True)
 h=pd.read_csv(folder/'history.csv');report['fold_histories'].append(dict(pid=pid,epochs=len(h),steps_per_epoch=32,
  updates=len(h)*32,draws=len(h)*32*256,last_loss=float(h.loss.iloc[-1]),seconds=float(h.seconds.sum())))
 del net
for name in ['isolated_activity_per_class.csv','isolated_sign_per_class.csv']:
 d=pd.read_csv(OUT/name).sort_values('f1-score')
 report[name]={'weakest':d.head(6).to_dict('records'),'strongest':d.tail(4).to_dict('records')}
