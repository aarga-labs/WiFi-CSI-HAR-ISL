for typ in ['activity','sign']:
 d=pred[pred.type.eq(typ)&pred.part.ne('scripts')&pred.label.ne(pred.pred)]
 report['top_confusions'][typ]=[dict(true=a,predicted=b,count=int(n)) for (a,b),n in d.groupby(['label','pred']).size().sort_values(ascending=False).head(8).items()]
report['summary']=pd.read_csv(OUT/'summary.csv').to_dict('records')
(BASE/'audit.json').write_text(json.dumps(report,indent=2))
